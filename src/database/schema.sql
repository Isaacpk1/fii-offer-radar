-- FII Warehouse
-- Banco analitico local para consolidar dados oficiais, mercado e metricas calculadas.
--
-- Convencoes:
-- - CNPJ fica em formato texto para preservar pontuacao quando vier da fonte.
-- - Datas usam DATE.
-- - Valores financeiros usam DOUBLE para facilitar ingestao via pandas/DuckDB.
-- - `fii_rendimentos` traz estimativa CVM; `oferta_projecoes` separa baseline historico de DY projetado.

