    cnpj VARCHAR PRIMARY KEY,
    ticker VARCHAR,
    nome VARCHAR,
    administrador VARCHAR,
    gestor VARCHAR,
    segmento VARCHAR,
    tipo_fii VARCHAR,
    codigo_isin VARCHAR,
    publico_alvo VARCHAR,
    mandato VARCHAR,
    fonte_principal VARCHAR,
    atualizado_em TIMESTAMP
);

